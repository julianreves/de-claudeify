#!/usr/bin/env node
// Builds everything the demos need, with headless Chrome and no dependencies:
//   demos/data.js          page heights, marker positions and scanner counts for the showcase
//   demos/<name>/*.png     a screenshot of every before and after page
//   demos/hero.png         the showcase with the slider in the middle (README header)
//   demos/showcase.gif     the slider sweeping across the page (README animation, needs ffmpeg)
// Usage: node demos/render.mjs [--no-gif]      (set CHROME=/path/to/chrome if it is not found)
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { MARKERS } from './markers.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CANDIDATES = [
  process.env.CHROME,
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/Applications/Chromium.app/Contents/MacOS/Chromium',
  '/usr/bin/google-chrome', '/usr/bin/google-chrome-stable', '/usr/bin/chromium', '/usr/bin/chromium-browser',
].filter(Boolean);
const CHROME = CANDIDATES.find((p) => fs.existsSync(p));
if (!CHROME) { console.error('Chrome not found. Set CHROME=/path/to/chrome.'); process.exit(1); }

const DEMOS = ['landing', 'dashboard', 'slide'];
const FIXED_HEIGHT = { slide: 2430 };
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'dc-chrome-'));
const chrome = (args) => spawnSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1', `--user-data-dir=${profile}`, ...args], { encoding: 'utf8', timeout: 90000, maxBuffer: 64 * 1024 * 1024 });
const url = (f, q = '') => pathToFileURL(f).href + q;

// Run a script inside a copy of the page and read its JSON result back from the dumped DOM.
function probe(file, body) {
  const tmp = path.join(path.dirname(file), '.probe.html');
  const code = `<script>(function(){var out=(function(){${body}})();var d=document.createElement('pre');d.id='__dc';d.textContent=JSON.stringify(out);document.body.appendChild(d);})();</script></body>`;
  fs.writeFileSync(tmp, fs.readFileSync(file, 'utf8').replace('</body>', code));
  try {
    const r = chrome(['--window-size=1440,1000', '--virtual-time-budget=1500', '--dump-dom', url(tmp)]);
    const m = r.stdout.match(/<pre id="__dc">([\s\S]*?)<\/pre>/);
    if (!m) throw new Error(`probe failed for ${file}`);
    return JSON.parse(m[1].replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>'));
  } finally { fs.rmSync(tmp, { force: true }); }
}

function scan(file) {
  const r = spawnSync(process.execPath, [path.join(HERE, '..', 'scripts', 'scan.mjs'), file, '--json'], { encoding: 'utf8' });
  return JSON.parse(r.stdout).summary;
}

const data = {};
for (const name of DEMOS) {
  const before = path.join(HERE, name, 'before.html');
  const after = path.join(HERE, name, 'after.html');
  const hb = FIXED_HEIGHT[name] || probe(before, 'return Math.ceil(document.documentElement.scrollHeight);');
  const ha = FIXED_HEIGHT[name] || probe(after, 'return Math.ceil(document.documentElement.scrollHeight);');
  const specs = MARKERS[name];
  const rects = probe(before, `var specs=${JSON.stringify(specs.map((m) => m.sel))};return specs.map(function(s){var e=document.querySelector(s);if(!e)return null;var r=e.getBoundingClientRect();var g=document.createRange();g.selectNodeContents(e);var tr=g.getBoundingClientRect();if(!tr.width)tr=r;return {l:r.left+scrollX,t:r.top+scrollY,w:r.width,h:r.height,tl:tr.left+scrollX,tt:tr.top+scrollY,th:tr.height};});`);
  const markers = specs.map((m, i) => {
    const r = rects[i];
    if (!r) throw new Error(`${name}: selector not found: ${m.sel}`);
    const left = m.at === 'left';
    return { n: i + 1, at: left ? 'left' : 'in', ax: Math.round(left ? r.tl : r.l), ay: Math.round(left ? r.tt + Math.min(r.th / 2, 30) : r.t), label: m.label, rules: m.rules };
  });
  const sb = scan(before), sa = scan(after);
  data[name] = { hb, ha, fail: sb.fail, warn: sb.warn, afterFail: sa.fail, afterWarn: sa.warn, markers };
  console.log(`${name}: before ${sb.fail} FAIL ${sb.warn} WARN, after ${sa.fail}/${sa.warn}, heights ${hb}/${ha}, ${markers.length} markers`);
}
fs.writeFileSync(path.join(HERE, 'data.js'), `// Generated by demos/render.mjs. Do not edit.\nwindow.DC_DEMOS = ${JSON.stringify(data, null, 2)};\n`);

// Screenshots of every page.
for (const name of DEMOS) {
  for (const side of ['before', 'after']) {
    const h = data[name][side === 'before' ? 'hb' : 'ha'];
    const out = path.join(HERE, name, `${side}.png`);
    chrome([`--window-size=1440,${h}`, `--screenshot=${out}`, '--virtual-time-budget=1500', url(path.join(HERE, name, `${side}.html`))]);
    console.log(`${name}/${side}.png`);
  }
}

// The showcase itself: a still for the README header and, if ffmpeg exists, a short animation.
const index = path.join(HERE, 'index.html');
const W = 1440, H = 1000;
const shot = (q, out) => chrome([`--window-size=${W},${H}`, `--screenshot=${out}`, '--virtual-time-budget=2500', url(index, q)]);
shot('?demo=landing&view=side&still=1', path.join(HERE, 'hero.png'));
console.log('hero.png');

if (!process.argv.includes('--no-gif') && spawnSync('ffmpeg', ['-version']).status === 0) {
  // One GIF per demo. It shows only the page: "Before" while it shows the generated version, "After" once the line moves,
  // then it holds on the finished page. y is the page offset the GIF starts at.
  const GIFS = { landing: 0, dashboard: 0, slide: 810 };
  const GW = 1280, GH = 800, SWEEP = 28;
  const ease = (t) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);
  for (const [name, y] of Object.entries(GIFS)) {
    const frames = fs.mkdtempSync(path.join(os.tmpdir(), 'dc-frames-'));
    const xs = [1];
    for (let i = 1; i <= SWEEP; i++) xs.push(1 - ease(i / SWEEP));
    xs[xs.length - 1] = 0;
    xs.forEach((x, i) => chrome([`--window-size=${GW},${GH}`, `--screenshot=${path.join(frames, `f${String(i).padStart(3, '0')}.png`)}`, '--virtual-time-budget=2500', url(index, `?demo=${name}&view=gif&still=1&x=${x.toFixed(3)}&y=${y}`)]));
    const list = xs.map((_, i) => `file '${path.join(frames, `f${String(i).padStart(3, '0')}.png`)}'\nduration ${i === 0 ? 1.4 : i === xs.length - 1 ? 2.2 : 0.06}`);
    list.push(`file '${path.join(frames, `f${String(xs.length - 1).padStart(3, '0')}.png`)}'`);
    fs.writeFileSync(path.join(frames, 'list.txt'), list.join('\n') + '\n');
    const out = path.join(HERE, `showcase-${name}.gif`);
    const r = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'concat', '-safe', '0', '-i', path.join(frames, 'list.txt'),
      '-vf', 'scale=900:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=128:stats_mode=diff[p];[b][p]paletteuse=dither=bayer:bayer_scale=3', '-loop', '0', out]);
    console.log(r.status === 0 ? `showcase-${name}.gif ${(fs.statSync(out).size / 1e6).toFixed(1)} MB` : 'ffmpeg failed: ' + r.stderr);
    fs.rmSync(frames, { recursive: true, force: true });
  }
}
fs.rmSync(profile, { recursive: true, force: true });
